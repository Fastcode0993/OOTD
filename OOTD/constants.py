SEASON_CLASSES: List[str] = ["Spring", "Summer", "Autumn", "Winter"]

# ── 톤 목록 ──────────────────────────────────────────────────
TONE_CLASSES: List[str] = ["Warm", "Bright", "Light"]

# ── 12클래스 (계절_톤) ─────────────────────────────────────────
# 순서: Spring_Warm, Spring_Bright, Spring_Light,
#       Summer_Warm, Summer_Bright, Summer_Light, ...
SEASON_TONE_CLASSES: List[str] = [
    f"{s}_{t}" for s in SEASON_CLASSES for t in TONE_CLASSES
]

def parse_season_tone(class_name: str):
    """
    'Spring_Warm' -> ('Spring', 'Warm')
    'Spring'      -> ('Spring', None)   (4클래스 모델 호환)
    """
    if "_" in class_name:
        parts = class_name.split("_", 1)
        return parts[0], parts[1]
    return class_name, None


